//   growth 成長型         starts / wins 戦績   earn 獲得賞金（万円、海外を含む概数）
//   rec   着度数 [1着, 2着, 3着, 着外]。分かっている馬だけ（無ければ 2 着以下は「—」）
//   big   主な勝鞍 [年, レース名, 格]
//   mare  繁殖牝馬として日本で産駒を出した年 [初年, 最終年]（産駒の生年）。最終年が null なら 2026 年も繁殖中
//
// 種付料は 2025 年 11 月〜2026 年 2 月に各スタリオンが発表した 2026 年度の額。
// 獲得賞金と能力の格はゲーム用の概数で、公式の記録ではない。

